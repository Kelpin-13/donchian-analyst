/**
 * Analyst.gs — the language layer.
 *
 * Hard rule enforced by design, not by prompt: the analyst never sees a
 * question like "should I buy?". By the time it is called, the signal has
 * already been decided by Strategy.gs. Its only jobs are to describe the
 * setup, name what would kill it, and later grade its own note against
 * what actually happened.
 */

function callClaude_(systemPrompt, userPrompt) {
  const key = secret_('ANTHROPIC_API_KEY', true);

  const res = UrlFetchApp.fetch('https://api.anthropic.com/v1/messages', {
    method: 'post',
    contentType: 'application/json',
    muteHttpExceptions: true,
    headers: {
      'x-api-key': key,
      'anthropic-version': '2023-06-01'
    },
    payload: JSON.stringify({
      model: CONFIG.ANALYST.model,
      max_tokens: CONFIG.ANALYST.maxTokens,
      system: systemPrompt,
      messages: [{ role: 'user', content: userPrompt }]
    })
  });

  if (res.getResponseCode() !== 200) {
    throw new Error('Anthropic API ' + res.getResponseCode() + ': ' +
                    res.getContentText().slice(0, 300));
  }

  const body = JSON.parse(res.getContentText());
  return body.content
    .filter(b => b.type === 'text')
    .map(b => b.text)
    .join('\n')
    .trim();
}

/** Ask for JSON, strip any fences, parse safely. Never let a bad reply crash the run. */
function callClaudeJson_(systemPrompt, userPrompt, fallback) {
  try {
    const raw = callClaude_(systemPrompt, userPrompt);
    const clean = raw.replace(/```json/g, '').replace(/```/g, '').trim();
    const start = clean.indexOf('{');
    const end = clean.lastIndexOf('}');
    if (start === -1 || end === -1) throw new Error('No JSON object in reply');
    return JSON.parse(clean.substring(start, end + 1));
  } catch (e) {
    logLine_('ANALYST_ERROR', e.message);
    return fallback;
  }
}

const ANALYST_SYSTEM =
  'You are a market analyst embedded in a rule-based trading research tool. ' +
  'The trading signal has ALREADY been generated by deterministic code. Your job ' +
  'is never to approve, reject, or predict — only to describe context and name ' +
  'what would invalidate the setup.\n' +
  'Rules:\n' +
  '- Be specific and plain. No hype, no "to the moon", no price targets.\n' +
  '- If the data is thin, say the context is thin rather than inventing a story.\n' +
  '- "confidence" means how cleanly this matches the strategy pattern. ' +
  'It is NOT a probability of profit.\n' +
  '- Output raw JSON only. No markdown, no preamble.';

/** Compact snapshot of recent price action, fed to the analyst as plain numbers. */
function marketContext_(candles, series, i) {
  const k = candles[i];
  const lookback = Math.min(30, i);
  const recent = candles.slice(i - lookback, i + 1);

  return {
    symbol: CONFIG.MARKET.symbol,
    candle: CONFIG.MARKET.intervalMinutes + 'm',
    barTime: Utilities.formatDate(new Date(k.t), CONFIG.TZ, 'yyyy-MM-dd HH:mm'),
    close: round_(k.c),
    ema100: round_(series.ema[i]),
    pctAboveEma: round_(pctChange_(series.ema[i], k.c)),
    atr: round_(series.atr[i]),
    atrPctOfPrice: round_((series.atr[i] / k.c) * 100),
    channelHigh20: round_(series.entry.upper[i]),
    channelLow10: round_(series.exit.lower[i]),
    change30Bars: round_(pctChange_(recent[0].c, k.c)),
    annualisedVolPct: round_(realisedVolPct_(candles.slice(0, i + 1), 60)),
    volumeVsAvg: round_(k.v / (recent.reduce((a, x) => a + x.v, 0) / recent.length))
  };
}

function round_(n) {
  return n === null || n === undefined ? null : Math.round(n * 100) / 100;
}

/** Pre-trade note, written the moment a signal fires. Immutable once logged. */
function writePreTradeNote_(sig, ctx) {
  if (!CONFIG.ANALYST.enabled) {
    return { setup: '(analyst disabled)', invalidation: '', watch: '', confidence: 'n/a' };
  }

  const prompt =
    'A ' + sig.type + ' signal just fired on closed-candle data.\n\n' +
    'Signal reason (from the rules engine): ' + sig.reason + '\n\n' +
    'Market snapshot:\n' + JSON.stringify(ctx, null, 2) + '\n\n' +
    'Return JSON with exactly these keys:\n' +
    '{"setup": "2-3 sentences on what this breakout looks like in context",\n' +
    ' "invalidation": "1-2 sentences: what price behaviour would show this setup failed",\n' +
    ' "watch": "one concrete thing to watch over the next few bars",\n' +
    ' "confidence": "low|medium|high"}';

  return callClaudeJson_(ANALYST_SYSTEM, prompt, {
    setup: '(analyst unavailable)', invalidation: '', watch: '', confidence: 'n/a'
  });
}

/** Daily plain-language regime brief. Runs once a day, independent of signals. */
function writeRegimeBrief_(candles, series) {
  const i = candles.length - 1;
  const ctx = marketContext_(candles, series, i);
  const state = getState_();

  const prompt =
    'Daily regime brief. No signal fired — this is background context.\n\n' +
    'Market snapshot:\n' + JSON.stringify(ctx, null, 2) + '\n' +
    'Current bot position: ' + state.position +
    (state.position === 'LONG'
      ? ' (entry ' + round_(state.entryPrice) + ', stop ' + round_(state.stop) + ')'
      : '') + '\n\n' +
    'The strategy is a 20-bar Donchian breakout that only takes longs above the ' +
    '100 EMA. Return JSON:\n' +
    '{"regime": "trending_up|trending_down|ranging|volatile_choppy",\n' +
    ' "summary": "3-4 sentences in plain language on what price is doing",\n' +
    ' "strategyFit": "1-2 sentences on whether this regime suits or fights a breakout system",\n' +
    ' "riskNote": "one honest sentence on the main risk in this environment"}';

  return callClaudeJson_(ANALYST_SYSTEM, prompt, {
    regime: 'unknown', summary: '(analyst unavailable)', strategyFit: '', riskNote: ''
  });
}

/**
 * The feedback loop. Hands the analyst its own old note plus the real outcome
 * and asks what it got wrong. This is the part that compounds.
 */
function gradeNote_(signalRow, outcome) {
  const prompt =
    'Grade an earlier analyst note against what actually happened.\n\n' +
    'ORIGINAL NOTE (written at signal time, ' + signalRow.time + '):\n' +
    '  setup: ' + signalRow.setup + '\n' +
    '  invalidation: ' + signalRow.invalidation + '\n' +
    '  watch: ' + signalRow.watch + '\n' +
    '  confidence: ' + signalRow.confidence + '\n\n' +
    'WHAT ACTUALLY HAPPENED over the next ' + CONFIG.ANALYST.gradeAfterBars + ' bars:\n' +
    JSON.stringify(outcome, null, 2) + '\n\n' +
    'Be blunt. If the note was vague enough to be right either way, say so.\n' +
    'Return JSON:\n' +
    '{"verdict": "accurate|partly_accurate|wrong|unfalsifiable",\n' +
    ' "lesson": "ONE sentence a trader could actually act on next time",\n' +
    ' "missedFactor": "what the original note failed to consider, or none"}';

  return callClaudeJson_(ANALYST_SYSTEM, prompt, {
    verdict: 'ungraded', lesson: '(analyst unavailable)', missedFactor: ''
  });
}